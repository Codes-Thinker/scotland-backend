import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import type { ObjectStorage } from './object-storage';

/**
 * Production storage: a private S3 bucket (decision D7). Credentials come from the standard
 * AWS chain (IAM role, environment, shared profile), never from the repository.
 * Works with S3-compatible services when S3_ENDPOINT is set.
 */
export class S3ObjectStorage implements ObjectStorage {
  constructor(
    private readonly client: Pick<S3Client, 'send'>,
    private readonly bucket: string,
  ) {}

  static create(opts: { bucket: string; region: string; endpoint?: string }): S3ObjectStorage {
    const client = new S3Client({
      region: opts.region,
      ...(opts.endpoint && { endpoint: opts.endpoint, forcePathStyle: true }),
    });
    return new S3ObjectStorage(client, opts.bucket);
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.client.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: safeKey(key),
        Body: body,
        ContentType: contentType,
        ServerSideEncryption: 'AES256',
      }),
    );
  }

  async get(key: string): Promise<Buffer> {
    const res = await this.client.send(
      new GetObjectCommand({ Bucket: this.bucket, Key: safeKey(key) }),
    );
    const bytes = await res.Body?.transformToByteArray();
    if (!bytes) throw new Error('Stored object is empty or missing');
    return Buffer.from(bytes);
  }

  async delete(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: safeKey(key) }));
  }
}

/** Keys are generated by the server; reject anything that looks like a path escape. */
function safeKey(key: string): string {
  const backslash = String.fromCharCode(92);
  if (!key || key.startsWith('/') || key.includes('..') || key.includes(backslash)) {
    throw new Error('Invalid storage key');
  }
  return key;
}
